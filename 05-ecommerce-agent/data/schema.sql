-- Storefront schema for the E-Commerce Agent.
--
-- Targets AlloyDB for PostgreSQL (or Cloud SQL / Postgres 15+ with pgvector).
-- The `embedding` column on products is what makes "something for trail
-- running in the wet" a searchable query rather than a keyword miss.
--
--   psql "$DATABASE_URL" -f data/schema.sql

CREATE EXTENSION IF NOT EXISTS vector;
-- google_ml_integration provides the in-database embedding() function on
-- AlloyDB and Cloud SQL. See schema_local.sql for plain Postgres.
CREATE EXTENSION IF NOT EXISTS google_ml_integration CASCADE;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- --------------------------------------------------------------------------
-- Customers
-- --------------------------------------------------------------------------
-- `email` is the join key for every personal query, and it is populated from a
-- *verified* Google token claim rather than from anything a user typed. The
-- UNIQUE constraint is what makes claim-based lookup unambiguous.
CREATE TABLE IF NOT EXISTS users (
    user_id    SERIAL PRIMARY KEY,
    email      VARCHAR(320) NOT NULL UNIQUE,
    full_name  VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- --------------------------------------------------------------------------
-- Catalogue
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    product_id       SERIAL PRIMARY KEY,
    name             VARCHAR(255) NOT NULL UNIQUE,
    brand            VARCHAR(100) NOT NULL,
    category         VARCHAR(100) NOT NULL,
    description      TEXT NOT NULL,
    popularity_score NUMERIC(4, 2) NOT NULL DEFAULT 0,
    embedding        vector(768),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- One row per sellable variant. Price lives here, not on the product, because
-- a size 48 and a size 40 of the same shoe can legitimately differ.
CREATE TABLE IF NOT EXISTS product_variants (
    variant_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    size       VARCHAR(20) NOT NULL,
    color      VARCHAR(60) NOT NULL,
    -- NUMERIC, never a float. Money in a float is money that rounds wrong.
    price      NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    sku        VARCHAR(64) UNIQUE,
    UNIQUE (product_id, size, color)
);

-- --------------------------------------------------------------------------
-- Stores and stock
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stores (
    store_id  SERIAL PRIMARY KEY,
    name      VARCHAR(255) NOT NULL UNIQUE,
    address   VARCHAR(500) NOT NULL,
    city      VARCHAR(100) NOT NULL,
    country   VARCHAR(100) NOT NULL,
    latitude  NUMERIC(9, 6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE IF NOT EXISTS inventory (
    store_id   INTEGER NOT NULL REFERENCES stores(store_id) ON DELETE CASCADE,
    variant_id INTEGER NOT NULL REFERENCES product_variants(variant_id) ON DELETE CASCADE,
    quantity   INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    PRIMARY KEY (store_id, variant_id)
);

-- --------------------------------------------------------------------------
-- Baskets
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS shopping_lists (
    list_id    SERIAL PRIMARY KEY,
    -- One open basket per customer, enforced here rather than hoped for in
    -- application code.
    user_id    INTEGER NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS shopping_list_items (
    item_id    SERIAL PRIMARY KEY,
    list_id    INTEGER NOT NULL REFERENCES shopping_lists(list_id) ON DELETE CASCADE,
    variant_id INTEGER NOT NULL REFERENCES product_variants(variant_id) ON DELETE CASCADE,
    quantity   INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    added_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Adding the same variant twice bumps the quantity instead of creating a
    -- duplicate line (see the ON CONFLICT in tools.yaml).
    UNIQUE (list_id, variant_id)
);

-- --------------------------------------------------------------------------
-- Delivery and orders
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS delivery_methods (
    method_id      SERIAL PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    description    VARCHAR(500) NOT NULL,
    cost           NUMERIC(10, 2) NOT NULL CHECK (cost >= 0),
    estimated_days VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
    order_id         SERIAL PRIMARY KEY,
    user_id          INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    store_id         INTEGER REFERENCES stores(store_id) ON DELETE SET NULL,
    method_id        INTEGER REFERENCES delivery_methods(method_id) ON DELETE SET NULL,
    status           VARCHAR(30) NOT NULL DEFAULT 'Pending',
    total_amount     NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    shipping_address VARCHAR(500) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT orders_status_check CHECK (status IN (
        'Pending', 'Confirmed', 'Packed', 'Shipped', 'Delivered',
        'Cancelled', 'Returned'
    ))
);

-- Line items snapshot the price at the time of ordering. Joining back to
-- product_variants for the price would silently rewrite order history the next
-- time someone runs a sale.
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id SERIAL PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    variant_id    INTEGER NOT NULL REFERENCES product_variants(variant_id) ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0)
);

-- --------------------------------------------------------------------------
-- Triggers and indexes
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION orders_touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS orders_set_updated_at ON orders;
CREATE TRIGGER orders_set_updated_at
    BEFORE UPDATE ON orders
    FOR EACH ROW
    EXECUTE FUNCTION orders_touch_updated_at();

CREATE INDEX IF NOT EXISTS products_brand_idx      ON products (brand);
CREATE INDEX IF NOT EXISTS products_category_idx   ON products (category);
CREATE INDEX IF NOT EXISTS products_name_trgm_idx  ON products USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS products_brand_trgm_idx ON products USING gin (brand gin_trgm_ops);
CREATE INDEX IF NOT EXISTS variants_product_idx    ON product_variants (product_id);
CREATE INDEX IF NOT EXISTS variants_size_idx       ON product_variants (size);
CREATE INDEX IF NOT EXISTS inventory_variant_idx   ON inventory (variant_id);
CREATE INDEX IF NOT EXISTS orders_user_idx         ON orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS order_items_order_idx   ON order_items (order_id);

